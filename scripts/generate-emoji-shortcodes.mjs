// Regenerates web/js/components/emoji-shortcodes.js (name → emoji only) from GitHub's gemoji list.
import fs from 'node:fs';
import { gemoji } from 'gemoji';

const version = JSON.parse(fs.readFileSync(new URL('../node_modules/gemoji/package.json', import.meta.url))).version;
const names = {};
gemoji.forEach((entry) => entry.names.forEach((name) => { names[name] = entry.emoji; }));
fs.writeFileSync(
  new URL('../web/js/components/emoji-shortcodes.js', import.meta.url),
  `// Generated by scripts/generate-emoji-shortcodes.mjs from gemoji ${version}; do not edit.\n`
    + `export default ${JSON.stringify(names)};\n`,
);
