// Rebuild the responsive README showcases after changing their source screenshots.
// Run from any directory: node scripts/generate-readme-showcases.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const assets = new URL('../docs/assets/showcase/', import.meta.url);
// Match the font stack used by GitHub's .markdown-body.
const fontFamily = "'Mona Sans VF', -apple-system, BlinkMacSystemFont, 'Segoe UI', 'Noto Sans Backtick Fix', 'Noto Sans', Helvetica, Arial, sans-serif, 'Apple Color Emoji', 'Segoe UI Emoji'";
const sections = [
  {
    name: 'tools',
    title: 'Developer tools',
    items: [
      ['project-files', 'Project', 'files'],
      ['git', 'Git', 'changes'],
      ['terminal', 'Mobile', 'terminal'],
      ['remote-preview', 'Remote', 'preview'],
    ],
  },
  {
    name: 'rendering',
    title: 'Rich rendering',
    items: [
      ['permissions', 'Permission', 'approvals'],
      ['mermaid', 'Mermaid', 'diagrams'],
      ['inline-html', 'Inline HTML', 'preview'],
      ['file-preview', 'File', 'preview'],
    ],
  },
];

for (const section of sections) {
  const images = await Promise.all(section.items.map(async ([name]) =>
    (await readFile(new URL(`${name}.avif`, assets))).toString('base64')));

  for (const columns of [4, 2]) {
    const mobile = columns === 2;
    const width = columns * 300;
    const rowHeight = mobile ? 724 : 688;
    const height = (section.items.length / columns) * rowHeight;
    const svg = [
      '<!-- Generated by scripts/generate-readme-showcases.mjs. -->',
      `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title">`,
      `  <title id="title">${section.title}</title>`,
      '  <style>',
      '    .caption { fill: #1f2328; }',
      '    @media (prefers-color-scheme: dark) { .caption { fill: #e6edf3; } }',
      '  </style>',
    ];

    section.items.forEach(([, first, second], index) => {
      const x = (index % columns) * 300;
      const y = Math.floor(index / columns) * rowHeight;
      svg.push(
        `  <image x="${x + 6}" y="${y}" width="288" height="628" href="data:image/avif;base64,${images[index]}"/>`,
        `  <text class="caption" x="${x + 150}" y="${y + 668}" font-family="${fontFamily}" font-weight="400" font-size="${mobile ? 28 : 26}" text-anchor="middle">${mobile ? `${first}<tspan x="${x + 150}" dy="32">${second}</tspan>` : `${first} ${second}`}</text>`,
      );
    });
    svg.push('</svg>', '');

    const output = new URL(`${section.name}-${mobile ? 'mobile' : 'desktop'}.svg`, assets);
    await writeFile(output, svg.join('\n'));
    console.log(fileURLToPath(output));
  }
}
