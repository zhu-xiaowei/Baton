// Rebuild the README's text-only caption strips after changing their labels.
// Screenshots are referenced directly by README.md and are never embedded here.
// Run from any directory: node scripts/generate-readme-showcases.mjs
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const assets = new URL('../docs/assets/showcase/', import.meta.url);
// Match the font stack used by GitHub's .markdown-body.
const fontFamily = "'Mona Sans VF', -apple-system, BlinkMacSystemFont, 'Segoe UI', 'Noto Sans Backtick Fix', 'Noto Sans', Helvetica, Arial, sans-serif, 'Apple Color Emoji', 'Segoe UI Emoji'";
const sections = [
  {
    name: 'tools',
    title: 'Developer tools',
    items: [
      ['project-files', 'Project', 'files'],
      ['git', 'Git', 'changes'],
      ['terminal', 'Mobile', 'terminal'],
      ['remote-preview', 'Remote', 'preview'],
    ],
  },
  {
    name: 'rendering',
    title: 'Rich rendering',
    items: [
      ['permissions', 'Permission', 'approvals'],
      ['mermaid', 'Mermaid', 'diagrams'],
      ['inline-html', 'Inline HTML', 'preview'],
      ['file-preview', 'File', 'preview'],
    ],
  },
];

for (const section of sections) {
  const layouts = [
    ['desktop', section.items],
    ['mobile', section.items.slice(0, 2)],
    ['mobile-second', section.items.slice(2)],
  ];
  for (const [layout, items] of layouts) {
    const width = items.length * 300;
    const svg = [
      '<!-- Generated by scripts/generate-readme-showcases.mjs. -->',
      `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="44" viewBox="0 0 ${width} 44">`,
      `  <title>${section.title} captions</title>`,
      '  <style>',
      '    text { fill: #1f2328; }',
      '    @media (prefers-color-scheme: dark) { text { fill: #e6edf3; } }',
      '  </style>',
      `  <g font-family="${fontFamily}" font-weight="400" font-size="${layout === 'desktop' ? 26 : 28}" text-anchor="middle">`,
      ...items.map(([, first, second], index) =>
        `    <text x="${index * 300 + 150}" y="30">${first} ${second}</text>`),
      '  </g>',
      '</svg>',
      '',
    ];
    const output = new URL(`${section.name}-${layout}.svg`, assets);
    await writeFile(output, svg.join('\n'));
    console.log(fileURLToPath(output));
  }
}

// A zero-size source hides the first caption strip on desktop without CSS.
await writeFile(new URL('empty.svg', assets),
  '<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0"/>\n');
